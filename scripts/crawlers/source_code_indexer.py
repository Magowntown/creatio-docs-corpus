@dataclass
class CSharpFile:
    path: str
    package: str
    filename: str
    namespace: str = ""
    classes: List[Dict] = field(default_factory=list)
    interfaces: List[str] = field(default_factory=list)
    base_classes: List[str] = field(default_factory=list)
    usings: List[str] = field(default_factory=list)
    attributes: List[str] = field(default_factory=list)
    methods: List[Dict] = field(default_factory=list)
    properties: List[Dict] = field(default_factory=list)
    line_count: int = 0
    is_autogenerated: bool = False
    category: str = "unknown"


@dataclass
class PackageIndex:
    name: str
    authored_cs: int = 0
    autogen_cs: int = 0
    js_files: int = 0
    descriptor: Dict = field(default_factory=dict)
    dependencies: List[str] = field(default_factory=list)
    category: str = "unknown"
    files: List[CSharpFile] = field(default_factory=list)
    patterns: List[str] = field(default_factory=list)
    entities: List[str] = field(default_factory=list)
    services: List[str] = field(default_factory=list)
    event_handlers: List[str] = field(default_factory=list)


# ─── C# Parser ───────────────────────────────────────────────────────────────

class CSharpParser:
    """Lightweight C# source file parser for pattern extraction."""

    # Patterns
    RE_NAMESPACE = re.compile(r'namespace\s+([\w.]+)')
    RE_CLASS = re.compile(r'(?:public|internal|private|protected)?\s*(?:abstract|sealed|static|partial)?\s*class\s+(\w+)(?:\s*:\s*(.+?))?(?:\s*\{|$)', re.MULTILINE)
    RE_INTERFACE = re.compile(r'(?:public|internal)?\s*interface\s+(\w+)')
    RE_METHOD = re.compile(r'(?:public|protected|private|internal|override|virtual|static|async)\s+(?:\w+(?:<[^>]+>)?)\s+(\w+)\s*\(([^)]*)\)')
    RE_PROPERTY = re.compile(r'(?:public|protected|private|internal)\s+(?:virtual|override|static)?\s*(\w+(?:<[^>]+>)?)\s+(\w+)\s*\{')
    RE_USING = re.compile(r'using\s+([\w.]+)\s*;')
    RE_ATTRIBUTE = re.compile(r'\[(\w+)(?:\(.*?\))?\]')

    # Pattern detection
    RE_ENTITY_EVENT = re.compile(r'(?:OnSaving|OnSaved|OnDeleting|OnDeleted|OnInserting|OnInserted|OnUpdating|OnUpdated)')
    RE_PROCESS_ELEMENT = re.compile(r'ProcessFlowElement|ProcessSchemaUserTask|BaseProcessParametersEditModule')
    RE_WEB_SERVICE = re.compile(r'(?:ServiceRoute|HttpHandler|IReadOnlyComposableRequestHandler|RestRoute)')
    RE_ESQL = re.compile(r'EntitySchemaQuery|new\s+Select\(|InsertQuery|UpdateQuery|DeleteQuery')
    RE_BUSINESS_RULE = re.compile(r'BusinessRuleModule|BusinessRule')

    def parse_file(self, path: Path, package_name: str) -> CSharpFile:
        """Parse a C# file and extract structure."""
        try:
            content = path.read_text(encoding='utf-8-sig', errors='replace')
        except Exception:
            return CSharpFile(path=str(path), package=package_name, filename=path.name)

        result = CSharpFile(
            path=str(path),
            package=package_name,
            filename=path.name,
            line_count=content.count('\n') + 1,
            is_autogenerated='Autogenerated' in str(path),
        )

        # Namespace
        ns_match = self.RE_NAMESPACE.search(content)
        result.namespace = ns_match.group(1) if ns_match else ""

        # Usings
        result.usings = self.RE_USING.findall(content)

        # Classes with base classes
        for match in self.RE_CLASS.finditer(content):
            class_name = match.group(1)
            bases = match.group(2)
            base_list = [b.strip() for b in bases.split(',')] if bases else []
            result.classes.append({
                'name': class_name,
                'bases': base_list,
            })
            result.base_classes.extend(base_list)

        # Interfaces
        result.interfaces = self.RE_INTERFACE.findall(content)

        # Methods (only for authored files to avoid noise)
        if not result.is_autogenerated:
            for match in self.RE_METHOD.finditer(content):
                result.methods.append({
                    'name': match.group(1),
                    'params': match.group(2).strip(),
                })

        # Properties (only for authored)
        if not result.is_autogenerated:
            for match in self.RE_PROPERTY.finditer(content):
                result.properties.append({
                    'type': match.group(1),
                    'name': match.group(2),
                })

        # Attributes
        result.attributes = list(set(self.RE_ATTRIBUTE.findall(content)))

        # Categorize
        result.category = self._categorize(content, result)

        return result

    def _categorize(self, content: str, result: CSharpFile) -> str:
        """Categorize the file by its patterns."""
        categories = []

        if self.RE_ENTITY_EVENT.search(content):
            categories.append("entity_event_handler")
        if self.RE_PROCESS_ELEMENT.search(content):
            categories.append("process_element")
        if self.RE_WEB_SERVICE.search(content):
            categories.append("web_service")
        if self.RE_ESQL.search(content):
            categories.append("data_access")
        if self.RE_BUSINESS_RULE.search(content):
            categories.append("business_rule")

        # Check base classes for patterns
        for cls in result.classes:
            for base in cls.get('bases', []):
                if 'EventListener' in base or 'EventSubProcess' in base:
                    categories.append("event_listener")
                elif 'BaseProcessUserTask' in base or 'ProcessUserTask' in base:
                    categories.append("process_user_task")
                elif 'BaseService' in base or 'RestService' in base:
                    categories.append("rest_service")
                elif 'BaseEntity' in base or 'Entity' == base:
                    categories.append("entity")
                elif 'BaseSchema' in base:
                    categories.append("schema")

        return ",".join(categories) if categories else "general"


